  describe('editor de estructura', () => {
    const estructura: TableRef = { database: DB, schema: 'public', table: 'estructura' }
    const load = () => sessions.tableStructure(sessionId, estructura)
    const alter = async (change: (d: TableDesign) => TableDesign | void, ref = estructura, id = sessionId, extra = {}) => {
      const structure = await sessions.tableStructure(sessionId, ref)
      let design = designFromStructure(structure)
      design = change(design) ?? design
      const expected = buildAlterStatements('postgres', ref, structure, design)
      return { expected, out: await sessions.alterTable(id, { ...ref, design, base: structureSignature(structure), expected, ...extra }) }
    }

    beforeAll(async () => {
      await run(`
        CREATE TABLE estructura (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          nombre varchar(40) COLLATE "C" NOT NULL,
          estado varchar(10) NOT NULL DEFAULT 'nuevo',
          doble integer GENERATED ALWAYS AS (id * 2) STORED,
          nota text NULL,
          codigo integer
        );
        COMMENT ON COLUMN estructura.nombre IS 'Nombre del cliente';
        CREATE INDEX idx_estado ON estructura (estado);
        INSERT INTO estructura (nombre, codigo) VALUES ('uno', 10), ('dos', 20);
        CREATE TABLE estructura_hija (id integer PRIMARY KEY, padre integer, CONSTRAINT fk_padre FOREIGN KEY (padre) REFERENCES estructura (id));
      `)
    })

    it('lee valores por defecto, comentarios, intercalación, IDENTITY y columnas calculadas', async () => {
      const { columns } = await load()
      const byName = Object.fromEntries(columns.map((c) => [c.name, c]))
      expect(byName.id).toMatchObject({ autoIncrement: true, defaultValue: null })
      expect(byName.nombre).toMatchObject({ comment: 'Nombre del cliente', collation: 'C', dataType: 'character varying(40)' })
      expect(byName.estado).toMatchObject({ defaultValue: "'nuevo'::character varying" })
      expect(byName.doble).toMatchObject({ generated: { expression: '(id * 2)', stored: true }, defaultValue: null })
      expect(buildAlterStatements('postgres', estructura, await load(), designFromStructure(await load()))).toEqual([])
    })

    it('renombra, cambia tipos, comentarios, añade y borra columnas e índices', async () => {
      const { expected, out } = await alter((d) => {
        d = renameColumn(d, 1, 'nombre_completo')
        d.columns[1]!.dataType = 'varchar(120)'
        d.columns[3]!.name = 'doble_id'
        d.columns.splice(4, 1) // nota
        d.columns.push({ original: null, name: 'email', dataType: 'text', nullable: false, defaultValue: "''", autoIncrement: false, primaryKey: false, comment: 'Correo' })
        d.indexes.push({ original: null, name: 'uq_email_nombre', columns: ['email', 'nombre_completo'], unique: true })
        d.indexes[0]!.columns = ['estado', 'email']
        return d
      })
      expect(out).toEqual({ executed: expected.length, total: expected.length })
      const after = await load()
      const byName = Object.fromEntries(after.columns.map((c) => [c.name, c]))
      expect(after.columns.map((c) => c.name)).toEqual(['id', 'nombre_completo', 'estado', 'doble_id', 'codigo', 'email'])
      expect(byName.nombre_completo).toMatchObject({ dataType: 'character varying(120)', comment: 'Nombre del cliente', collation: 'C', nullable: false })
      expect(byName.doble_id!.generated).toMatchObject({ stored: true })
      expect(byName.email).toMatchObject({ defaultValue: "''::text", comment: 'Correo', nullable: false })
      expect(after.indexes.find((i) => i.name === 'uq_email_nombre')).toMatchObject({ columns: ['email', 'nombre_completo'], unique: true })
      expect(after.indexes.find((i) => i.name === 'idx_estado')).toMatchObject({ columns: ['estado', 'email'] })
      const page = await sessions.fetchTableData(sessionId, { ...estructura, offset: 0, limit: 10, sort: [{ column: 'nombre_completo', direction: 'asc' }] })
      expect(page.rows.map((r) => r[1])).toEqual(['dos', 'uno'])
    })

    it('quita y pone IDENTITY; la secuencia nueva sigue al valor más alto', async () => {
      const off = await alter((d) => void (d.columns[0]!.autoIncrement = false))
      expect(off.out.error).toBeUndefined()
      expect((await load()).columns[0]!.autoIncrement).toBe(false)
      const on = await alter((d) => {
        const codigo = d.columns.find((c) => c.name === 'codigo')!
        codigo.autoIncrement = true
        codigo.nullable = false
      })
      expect(on.out.error).toBeUndefined()
      await sessions.saveRowChanges(sessionId, { ...estructura, inserts: [[{ column: 'id', value: 3 }, { column: 'nombre_completo', value: 'tres' }]] })
      const out = await run('SELECT codigo FROM estructura WHERE id = 3')
      expect(out.results[0]!.rows[0]).toEqual([21])
    })

    it('cambia la clave primaria y el valor por defecto; si otra tabla depende de la clave, no toca nada', async () => {
      const change = (d: TableDesign) => {
        const estado = d.columns.find((c) => c.name === 'estado')!
        estado.defaultValue = "'pendiente'"
        estado.primaryKey = true
      }
      // fk_padre de estructura_hija usa la clave primaria: PostgreSQL no deja quitarla (sin CASCADE).
      const blocked = await alter(change)
      expect(blocked.out).toMatchObject({ executed: 0 })
      expect(blocked.out.error).toMatch(/depend/)
      expect((await load()).columns.find((c) => c.name === 'estado')?.defaultValue).toBe("'nuevo'::character varying")
      await run('ALTER TABLE estructura_hija DROP CONSTRAINT fk_padre')
      const { out } = await alter(change)
      expect(out.error).toBeUndefined()
      const after = await load()
      expect(after.indexes.find((i) => i.primary)).toMatchObject({ name: 'estructura_pkey', columns: ['id', 'estado'] })
      expect(after.columns.find((c) => c.name === 'estado')?.defaultValue).toBe("'pendiente'::character varying")
    })

    it('si una sentencia falla no queda nada aplicado (el DDL va en una transacción)', async () => {
      const hija: TableRef = { database: DB, schema: 'public', table: 'estructura_hija' }
      await run('ALTER TABLE estructura_hija ADD CONSTRAINT fk_padre FOREIGN KEY (padre) REFERENCES numeros (n)')
      const { expected, out } = await alter((d) => {
        d.dropForeignKeys = ['fk_padre']
        d.columns[1]!.dataType = 'tipo_que_no_existe'
      }, hija)
      expect(expected).toHaveLength(2)
      expect(out).toMatchObject({ executed: 0, total: 2 })
      expect(out.error).toMatch(/Sentencia 2 de 2: .*tipo_que_no_existe/)
      expect((await sessions.tableStructure(sessionId, hija)).foreignKeys).toHaveLength(1)
    })

    it('el error trae la pista de PostgreSQL (USING) y no cambia nada', async () => {
      const { out } = await alter((d) => void (d.columns.find((c) => c.name === 'email')!.dataType = 'integer'))
      expect(out.error).toMatch(/USING/)
      expect((await load()).columns.find((c) => c.name === 'email')?.dataType).toBe('text')
    })

    it('si la tabla cambió desde que se cargó, o el SQL no es el revisado, no aplica nada', async () => {
      const structure = await load()
      const design = designFromStructure(structure)
      design.columns[2]!.dataType = 'varchar(30)'
      const expected = buildAlterStatements('postgres', estructura, structure, design)
      await run("COMMENT ON COLUMN estructura.estado IS 'de otra persona'")
      await expect(sessions.alterTable(sessionId, { ...estructura, design, base: structureSignature(structure), expected })).rejects.toThrow(/ha cambiado/)
      const fresh = await load()
      await expect(sessions.alterTable(sessionId, { ...estructura, design, base: structureSignature(fresh), expected: ['SELECT 1'] })).rejects.toThrow(/no coincide/)
    })

    it('tablas de otro esquema', async () => {
      const pedidos: TableRef = { database: DB, schema: 'ventas', table: 'Pedidos' }
      const { out } = await alter((d) => {
        d.columns.push({ original: null, name: 'Total', dataType: 'numeric(10,2)', nullable: true, defaultValue: '0', autoIncrement: false, primaryKey: false, comment: null })
        d.indexes.push({ original: null, name: 'idx_cliente', columns: ['Cliente'], unique: false })
      }, pedidos)
      expect(out.error).toBeUndefined()
      const after = await sessions.tableStructure(sessionId, pedidos)
      expect(after.columns.map((c) => c.name)).toEqual(['Id', 'Cliente', 'creado', 'Total'])
      expect(after.indexes.map((i) => i.name)).toEqual(['Pedidos_pkey', 'idx_cliente'])
      const dropIndex = await alter((d) => void (d.indexes = []), pedidos)
      expect(dropIndex.expected).toEqual(['DROP INDEX "ventas"."idx_cliente"'])
      expect(dropIndex.out.error).toBeUndefined()
    })
  })

